"""Inject evaluation results into README.md, docs/REPORT.md and docs/DEVPOST.md.

    python scripts/fill_report.py [--url http://ELASTIC_IP]

Reads eval/results/{real,synthetic}/summary.json and eval/results/benchmark.json.
Every number in the docs comes from those files.

* README.md / REPORT.md: values live between invisible markers
  <!--V:NAME-->value<!--/V--> and result blocks between
  <!-- RESULTS:START --> ... <!-- RESULTS:END -->, so re-running always updates them.
  Values with no source file yet stay as {{NAME}} placeholders.
* docs/DEVPOST.md is rendered from docs/templates/DEVPOST.template.md.
* If pandoc is installed, docs/REPORT.html (and REPORT.pdf when a PDF engine exists) is exported.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "eval" / "results"
V_RE = re.compile(r"<!--V:(\w+)-->(.*?)<!--/V-->", re.S)


def load(p: Path) -> dict | None:
    return json.loads(p.read_text()) if p.exists() else None


def pct(x) -> str | None:
    return None if x is None else f"{x * 100:.0f}%"


def num(x, nd=2) -> str | None:
    return None if x is None else f"{x:.{nd}f}"


def dataset_values(prefix: str, s: dict | None) -> dict:
    if not s:
        return {}
    t = s["test"]
    w, b, nc = t["watershed"], t["baseline"], t["watershed_no_cluster"]
    hc = s.get("accuracy_by_confidence_test", {}).get("high", {})
    v = {
        f"{prefix}_N": s["n_images"], f"{prefix}_N_TUNE": s["n_tune"], f"{prefix}_N_TEST": s["n_test"],
        f"{prefix}_EXACT": pct(w["exact_acc"]), f"{prefix}_WITHIN1": pct(w["within1_acc"]),
        f"{prefix}_MAE": num(w["mae"]), f"{prefix}_MAPE": num(w["mape_pct"], 1), f"{prefix}_BIAS": f"{w['bias']:+.2f}",
        f"{prefix}_BASE_EXACT": pct(b["exact_acc"]), f"{prefix}_BASE_MAE": num(b["mae"]),
        f"{prefix}_NOCLUSTER_MAE": num(nc["mae"]), f"{prefix}_NOCLUSTER_EXACT": pct(nc["exact_acc"]),
        f"{prefix}_TUNED_PEAK": s["tuned_peak_ratio"],
        f"{prefix}_LAT_P50": s["latency_ms"]["p50"], f"{prefix}_LAT_P95": s["latency_ms"]["p95"],
        f"{prefix}_LAT_ARCH": s["machine"]["arch"],
        f"{prefix}_HIGHCONF_N": hc.get("n"), f"{prefix}_HIGHCONF_EXACT": pct(hc.get("exact_acc")) if hc.get("n") else None,
    }
    dc = s.get("deployed_check")
    if dc:
        v.update({"CONSIST_MATCHES": dc["matches"], "CONSIST_N": dc["n"], "CONSIST_RATE": pct(dc["match_rate"]),
                  "CONSIST_DATASET": s["dataset"], "LIVE_ARCH": dc["health"].get("arch"),
                  "LIVE_INSTANCE": dc["health"].get("instance_type"),
                  "CONSIST_E2E_P50": dc["e2e_latency_ms"]["p50"], "LIVE_URL": dc["url"]})
    return v


def results_block(real: dict | None, syn: dict | None, bench: dict | None) -> str:
    parts = ["<!-- generated by scripts/fill_report.py; do not edit by hand -->", ""]
    for s, label in [(real, "Real phone photos"), (syn, "Synthetic images (generated, NOT real photos)")]:
        if not s:
            parts += [f"**{label}:** {{{{{'REAL' if 'Real' in label else 'SYN'}_RESULTS_PENDING}}}}", ""]
            continue
        md = (RES / s["dataset"] / "summary.md").read_text().split("\n")
        body = [ln for ln in md if not ln.startswith("# ")]
        parts += [f"#### {label}", ""] + body + [""]
    if bench:
        e, sv = bench["e2e_latency_ms"], bench["server_pipeline_ms"]
        h = bench.get("health", {})
        parts += ["#### Live endpoint benchmark", "",
                  f"Target `{bench['url']}` ({h.get('instance_type')}, {h.get('arch')}, OpenCV {h.get('opencv_version')}); "
                  f"client-side timing including upload from the benchmarking machine.", "",
                  "| Requests | Concurrency | Errors | E2E p50 | E2E p95 | E2E p99 | Server pipeline p50 | Throughput |",
                  "|---:|---:|---:|---:|---:|---:|---:|---:|",
                  f"| {bench['n_requests']} | {bench['concurrency']} | {bench['errors']} | {e['p50']} ms | {e['p95']} ms | "
                  f"{e['p99']} ms | {sv['p50']} ms | {bench['throughput_rps']} req/s |", ""]
    else:
        parts += ["**Live endpoint benchmark:** {{BENCHMARK_PENDING}}", ""]
    return "\n".join(parts)


def fill_markers(text: str, values: dict) -> str:
    def rep(m):
        k = m.group(1)
        v = values.get(k)
        return f"<!--V:{k}-->{v if v is not None else '{{' + k + '}}'}<!--/V-->"
    return V_RE.sub(rep, text)


def fill_block(text: str, block: str) -> str:
    return re.sub(r"(<!-- RESULTS:START -->)(.*?)(<!-- RESULTS:END -->)",
                  lambda m: m.group(1) + "\n" + block + "\n" + m.group(3), text, flags=re.S)


def fill_template(text: str, values: dict) -> str:
    return re.sub(r"\{\{(\w+)\}\}", lambda m: str(values[m.group(1)]) if values.get(m.group(1)) is not None
                  else m.group(0), text)


def export_report() -> None:
    if not shutil.which("pandoc"):
        print("pandoc not found: skipping REPORT.pdf export")
        return
    src = ROOT / "docs" / "REPORT.md"
    common = ["pandoc", str(src), "--resource-path", str(ROOT / "docs"), "-s", "--metadata", "title=TabCount technical report"]
    r = subprocess.run(common + ["-o", str(ROOT / "docs" / "REPORT.pdf")], capture_output=True, text=True)
    if r.returncode == 0:
        print("exported docs/REPORT.pdf")
        return
    r = subprocess.run(common + ["--embed-resources", "-o", str(ROOT / "docs" / "REPORT.html")], capture_output=True, text=True)
    print("exported docs/REPORT.html (no PDF engine; print it to PDF from a browser)" if r.returncode == 0
          else f"pandoc export failed: {r.stderr[:200]}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--url", default=None, help="live URL (default: from benchmark/consistency results)")
    ap.add_argument("--no-export", action="store_true")
    a = ap.parse_args()

    real, syn, bench = load(RES / "real" / "summary.json"), load(RES / "synthetic" / "summary.json"), load(RES / "benchmark.json")
    values: dict = {}
    values.update(dataset_values("SYN", syn))
    values.update(dataset_values("REAL", real))
    if bench:
        e = bench["e2e_latency_ms"]
        values.update({"BENCH_N": bench["n_requests"], "BENCH_CONC": bench["concurrency"], "BENCH_ERRORS": bench["errors"],
                       "BENCH_P50": e["p50"], "BENCH_P95": e["p95"], "BENCH_P99": e["p99"],
                       "BENCH_RPS": bench["throughput_rps"], "BENCH_SERVER_P50": bench["server_pipeline_ms"]["p50"],
                       "LIVE_INSTANCE": bench.get("health", {}).get("instance_type") or values.get("LIVE_INSTANCE"),
                       "LIVE_ARCH": bench.get("health", {}).get("arch") or values.get("LIVE_ARCH")})
        values.setdefault("LIVE_URL", bench["url"])
    if a.url:
        values["LIVE_URL"] = a.url.rstrip("/")
    if values.get("LIVE_URL") and not str(values["LIVE_URL"]).endswith("/"):
        values["LIVE_URL"] = str(values["LIVE_URL"]) + "/"

    block = results_block(real, syn, bench)
    for rel in ["README.md", "docs/REPORT.md"]:
        p = ROOT / rel
        if p.exists():
            p.write_text(fill_block(fill_markers(p.read_text(), values), block))
            print(f"updated {rel}")
    tpl = ROOT / "docs" / "templates" / "DEVPOST.template.md"
    if tpl.exists():
        (ROOT / "docs" / "DEVPOST.md").write_text(fill_template(tpl.read_text(), values))
        print("rendered docs/DEVPOST.md")

    pending = sorted(set(re.findall(r"\{\{(\w+)\}\}", "".join(
        (ROOT / f).read_text() for f in ["README.md", "docs/REPORT.md", "docs/DEVPOST.md"] if (ROOT / f).exists()))))
    if pending:
        print("STILL PLACEHOLDERS (no results file yet): " + ", ".join(pending))
    if not a.no_export:
        export_report()


if __name__ == "__main__":
    sys.exit(main())
